#!/usr/bin/env bash
# End-to-end test in a throwaway container: bash test/run.sh debian:12|ubuntu:24.04
set -euo pipefail
IMAGE=${1:-ubuntu:24.04}
cd "$(dirname "$0")/.."
docker run --rm -i --label postgres-manager-test=1 -v "$PWD:/src:ro" "$IMAGE" bash -s <<'INNER'
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq >/dev/null
apt-get install -y -qq postgresql cron curl >/dev/null 2>&1
. /etc/os-release
echo "=== $PRETTY_NAME"
V=$(ls /etc/postgresql); pg_ctlcluster "$V" main start
mkdir -p /home/forge/app.example.com
printf 'APP_NAME=demo\nAPP_ENV=production\nDB_CONNECTION=pgsql\nDB_HOST=127.0.0.1\nDB_PORT=5432\nDB_DATABASE=app\nDB_USERNAME=forge\nDB_PASSWORD="secret"\n' > /home/forge/app.example.com/.env
runuser -u postgres -- psql -qc "create database app" -c "\c app" -c "create table t as select g id, md5(g::text) v from generate_series(1,100000) g"
cp /src/postgres-manager /root/pgm  # generated by: make build && chmod +x /root/pgm
PGM=/root/pgm
pgdg_answer=""; grep -rqs apt.postgresql.org /etc/apt/ || pgdg_answer="y"
echo "=== setup"
printf '%s' "${pgdg_answer:+$pgdg_answer
}" > /tmp/answers
printf '\n3\n\n\ny\n\n\n\n\n' >> /tmp/answers
$PGM setup < /tmp/answers
echo "=== status"; $PGM status
echo "=== menu (list, quit)"; printf '1\nq\n' | $PGM | grep -E "Backups ·|Choose" | head -3
runuser -u postgres -- psql -qd app -c "insert into t select g, 'after-full' from generate_series(100001,100500) g"
sleep 2; T=$(date '+%Y-%m-%d %H:%M:%S'); sleep 2
runuser -u postgres -- psql -qd app -c "insert into t select g, 'after-target' from generate_series(200001,200500) g" -c "select pg_switch_wal()" >/dev/null
echo "=== backup diff"; $PGM backup diff
echo "=== cron-backup incr"; $PGM cron-backup incr
echo "=== list"; $PGM list
echo "=== verify"; $PGM verify
echo "=== restore --time $T --target-dir"; $PGM restore --time "$T" --target-dir /var/lib/postgresql/pitr --yes
echo "rows in PITR copy (expect 100500):"; runuser -u postgres -- psql -XAtq -h /var/lib/postgresql/pitr -p 54330 -d app -c "select count(*) from t"
runuser -u postgres -- /usr/lib/postgresql/$V/bin/pg_ctl -D /var/lib/postgresql/pitr -s stop
echo "=== extensions (pg_stat_statements)"; printf '5\n\napp\n' | $PGM extensions; runuser -u postgres -- psql -XAtqd app -c 'select count(*) > 0 from pg_stat_statements'
echo "=== edit retention→14"; printf '2\n14\n9\n' | $PGM edit; grep retention /etc/pgbackrest/pgbackrest.conf; cat /etc/cron.d/postgres-manager
echo "=== live restore latest"; runuser -u postgres -- psql -qd app -c "drop table t"; runuser -u postgres -- psql -qc "select pg_switch_wal()" >/dev/null; sleep 3
LABEL=$(runuser -u postgres -- pgbackrest --stanza=main --output=json info | jq -r '.[0].backup[-1].label')
$PGM restore --set "$LABEL" --yes
echo "rows after live restore of last set (expect 101000):"; runuser -u postgres -- psql -XAtqd app -c "select count(*) from t"
echo "=== final status"; $PGM status
INNER
